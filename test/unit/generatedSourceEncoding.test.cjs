test('generated headers decode UTF-8 and both UTF-16 BOMs within the same byte limit',()=>{
 const text='// Copyright ©\r\n// <auto-generated/>\r\nclass Generated {}';
 for(const [name,encode] of Object.entries(encodings)){
  const bytes=encode(text),before=Buffer.from(bytes);
  assert.equal(sourceText(bytes),text,name);assert.equal(isGeneratedSource('/Generated.cs',bytes),true,name);assert.deepEqual(bytes,before);
  assert.equal(isGeneratedSource('/Ordinary.cs',encode('class C { string Header => "<auto-generated/>"; }')),false,name);
  assert.equal(isGeneratedSource('/Late.cs',encode(' '.repeat(2050)+'// <auto-generated/>')),false,name);
  const prefix=encode(' '.repeat(1100)+'// <auto-generated/>');
  assert.equal(isGeneratedSource('/Boundary.cs',prefix),!name.startsWith('utf16'),`${name}: bytes, not character count`);
 }
 const odd=Buffer.concat([encodings.utf16be(text),Buffer.from([0])]);
 assert.equal(sourceText(odd),text,'a partial final code unit is ignored');
});

test('UTF-16 generated inputs retain analysis aliases without entering tracked hashes',async t=>{
 const root=normalizePath(await fs.mkdtemp(path.join(os.tmpdir(),'testy-encoded-sources-')));t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const file=path.join(root,'Generated.cs'),sources=new SourceTracker();sources.setFiles([file]);
 const alias='global using IgnoreCoverage = System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverageAttribute;';
 for(const encode of [encodings.utf16le,encodings.utf16be]){
  await fs.writeFile(file,encode('// <auto-generated/>\n'+alias));await sources.refresh([file]);
  assert.equal(sources.isGenerated(file),true);assert.equal(sources.hashes.has(file),false);
  assert.ok(sources.analysisHashes.has(file));assert.ok(sources.aliasSources.get(file)?.includes(alias));
  await fs.writeFile(file,encode(alias+'\nclass Ordinary {}'));await sources.refresh([file]);
  assert.equal(sources.isGenerated(file),false);assert.ok(sources.hashes.has(file));
 }
});

test('editor disk classification observes UTF-16 saves, header removal and generated deletion',async t=>{
 const root=normalizePath(await fs.mkdtemp(path.join(os.tmpdir(),'testy-encoded-events-')));t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const {ui,handlers}=editor();t.after(()=>ui.dispose());ui.roots=[root];
 const requests=/** @type {unknown[][]} */([]);ui.scheduler.request=(/** @type {unknown[]} */...args)=>requests.push(args);ui.engine.markChanged=async()=>{};
 const file=normalizePath(path.join(root,'Generated.cs')),uri={scheme:'file',fsPath:file};
 for(const encode of [encodings.utf16le,encodings.utf16be]){
  await fs.writeFile(file,encode('// <auto-generated/>\n'));
  // Exercise the real save callback, then await its asynchronous disk handler.
  let saved;const changed=ui.changed.bind(ui);ui.changed=(/** @type {unknown[]} */...args)=>saved=changed(...args);
  handlers.save({uri,getText:()=>{throw new Error('The byte prefix must come from the saved encoding.');}});await saved;ui.changed=changed;
  assert.equal(requests.length,0);assert.equal(ui.engine.sources.isGenerated(file),true);
  await fs.rm(file);await ui.changed(uri,undefined,true);assert.equal(requests.length,0);
 }
 await fs.writeFile(file,encodings.utf16be('class C { string Header => "<auto-generated/>"; }'));await ui.changed(uri);
 assert.equal(requests.length,1);assert.equal(ui.engine.sources.isGenerated(file),false);
});
