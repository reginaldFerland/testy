// @ts-check
const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs/promises'),path=require('node:path'),os=require('node:os');
const {SourceTracker}=require('../../out/services/sources');
const {normalizePath}=require('../../out/core/paths');
const {loadUi}=require('./support/ui.cjs');
test('handwritten code containing generator marker strings must remain tracked',async t=>{
 const root=normalizePath(await fs.mkdtemp(path.join(os.tmpdir(),'testy-review9-marker-')));t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const source=path.join(root,'GeneratorTests.cs'),content='public class GeneratorTests { public string ExpectedHeader() => "<auto-generated/>"; }';
 await fs.writeFile(source,content);
 const sources=new SourceTracker();sources.setFiles([source]);await sources.refresh([source]);
 const ui=loadUi({vscode:{}});
 const requests=/** @type {unknown[][]} */([]);
 const context={queueChanged(){},disposed:false,roots:[root],config:{excludes:[],pattern:'**/*.cs'},scheduler:{request:(/** @type {unknown[]} */...args)=>requests.push(args)},
  engine:{knownFiles:[source],directories:[root],sources,markChanged:async()=>{}}};
 await ui.changeWatcher(context).changed({scheme:'file',fsPath:source},content);
 assert.equal(sources.hashes.has(source),true,'a string literal must not exclude handwritten input');
 assert.equal(requests.length,1);
});

test('generated headers are leading comment declarations, not marker examples or literals',()=>{
 const {isGeneratedSource}=require('../../out/core/paths');
 const headers=['// <auto-generated/>','\ufeff\n// Copyright\n// <AUTO-GENERATED>\n// Tool output',
  '/*\n * <auto-generated/>\n */\nclass C {}','/// <auto-generated/>'];
 const ordinary=['public class C { public string Header => "<auto-generated/>"; }',
  '// Detects <auto-generated> markers.\nclass C {}', '/* An example: <auto-generated/> */',
  'class C {}\n// <auto-generated/>', 'const string Expected = """\n// <auto-generated/>\n""";'];
 for(const content of headers)assert.equal(isGeneratedSource('/Code.cs',content),true,content);
 for(const content of ordinary)assert.equal(isGeneratedSource('/Code.cs',content),false,content);
});
