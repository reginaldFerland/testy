const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises'),path=require('node:path'),os=require('node:os');
const {TestEngine}=require('../../out/services/engine');
const {ProjectIndex}=require('../../out/core/selection');
const {normalizePath}=require('../../out/core/paths');

/**
 * @param {import('node:test').TestContext} t
 * @param {string} trigger
 */
async function fixture(t,trigger){
 const root=normalizePath(await fs.mkdtemp(path.join(os.tmpdir(),'testy-sweep-')));t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const file=(/** @type {string} */ name)=>path.join(root,name),files=[file('A.cs'),file('B.cs'),file('C.cs')];
 for(const name of files){await fs.writeFile(name,`class ${path.basename(name,'.cs')} {}`);}
 /** @type {any} Partial configuration mock: only the fields the engine reads here, plus `trigger`. */
 const config={trigger,testArguments:[],mode:'affected',coverage:true,excludes:[]};
 /** @type {any} Partial events/options mock; any also reaches the engine's private state (initialized, baseline, startRun). */
 const engine=new TestEngine(/** @type {any} */ ({roots:[root],storage:path.join(root,'state'),events:{output(){},coverage(){},phase(){}},configuration:()=>config}));
 engine.sources.setFiles(files);await engine.sources.refresh(files);
 engine.projects=[{file:file('P.csproj'),sourceFiles:files,references:[]}];engine.index=new ProjectIndex(engine.projects);
 engine.initialized=true;engine.structureDirty=false;
 /** @type {string[][]} */ const refreshed=[];const refresh=engine.sources.refresh.bind(engine.sources);
 engine.sources.refresh=(/** @type {string[]} */ list,/** @type {AbortSignal|undefined} */ signal)=>{refreshed.push([...list].map(name=>path.basename(name)).sort());return refresh(list,signal);};
 const start=(/** @type {string[]} */ files=[],full=false)=>engine.startRun({files,full},new AbortController(),undefined,false);
 return {engine,file,refreshed,start,config};
}

test('file-system triggered runs read only reported and marked files, without missing either',async t=>{
 const f=await fixture(t,'fileSystem');
 await fs.writeFile(f.file('A.cs'),'class A { int x; }');await fs.writeFile(f.file('B.cs'),'class B { int y; }');
 await f.engine.markChanged([f.file('B.cs')]);
 const run=await f.start([f.file('A.cs')]);
 assert.deepEqual(f.refreshed,[['A.cs']],'no sweep of every known input');
 assert.deepEqual(run.changes.map((/** @type {string} */ name)=>path.basename(name)).sort(),['A.cs','B.cs'],'a marked file is reread even when the batch omits it');
 assert.equal(run.structural,false);
 assert.equal(f.engine.hashes.get(f.file('B.cs')),require('../../out/core/paths').contentHash('class B { int y; }'));
});

test('first, full, structural, manual and save-triggered runs still sweep every input',async t=>{
 const f=await fixture(t,'save');
 await fs.writeFile(f.file('C.cs'),'class C { int z; }');
 const run=await f.start([f.file('A.cs')]);
 assert.deepEqual(f.refreshed,[['A.cs','B.cs','C.cs']],'saves alone cannot see external edits');
 assert.ok(run.changes.includes(f.file('C.cs')));
 f.config.trigger='fileSystem';
 for(const prepare of [()=>{f.engine.initialized=false;},()=>{f.engine.structureDirty=true;}]){
  f.refreshed.length=0;f.engine.initialized=true;f.engine.structureDirty=false;f.engine.baseline=undefined;prepare();
  await f.start([]);assert.deepEqual(f.refreshed,[['A.cs','B.cs','C.cs']]);
 }
 f.refreshed.length=0;f.engine.initialized=true;f.engine.structureDirty=false;f.engine.baseline=undefined;
 await f.start([],true);assert.deepEqual(f.refreshed,[['A.cs','B.cs','C.cs']],'a full refresh');
 f.refreshed.length=0;f.engine.baseline=undefined;
 await f.engine.startRun({files:[],full:false},new AbortController(),{groups:new Set()},true);assert.deepEqual(f.refreshed,[['A.cs','B.cs','C.cs']],'a manual run');
});

test('a generated-header classification from the watcher rereads the file on the next incremental run',async t=>{
 const f=await fixture(t,'fileSystem');
 await fs.writeFile(f.file('C.cs'),'// <auto-generated/>\nclass C {}');
 f.engine.sources.observeGenerated(f.file('C.cs'),true);
 const run=await f.start([]);
 assert.ok(run.changes.includes(f.file('C.cs')));assert.equal(f.engine.hashes.has(f.file('C.cs')),false);
});
