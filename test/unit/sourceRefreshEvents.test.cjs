const {test}=require('node:test');
const assert=require('node:assert/strict');
const io=require('node:fs/promises'),path=require('node:path'),os=require('node:os');
const {SourceTracker}=require('../../out/services/sources');
const {normalizePath,defaultExcludes}=require('../../out/core/paths');
const {loadUi}=require('./support/ui.cjs');

/** @param {import('node:test').TestContext} t */
async function temporary(t) {
 const root=normalizePath(await io.mkdtemp(path.join(os.tmpdir(),'testy-review7-')));t.after(()=>io.rm(root,{recursive:true,force:true}));return root;
}

test('a full refresh supersedes generated-file event classification before deletion',async t=>{
 const root=await temporary(t),file=path.join(root,'Stamped.cs'),sources=new SourceTracker(),ui=loadUi();
 /** @type {unknown[][]} */ const requests=[];
 sources.setFiles([file]);await io.writeFile(file,'// <auto-generated/>\nclass Stamped {}');
 // Partial ChangeWatcher host (any): only what the watcher reads.
 /** @type {any} */ const context={queueChanged(/** @type {string[]} */ files){void this.engine.markChanged(files);},roots:[root],config:{pattern:'**/*.cs',excludes:[]},engine:{knownFiles:[file],directories:[],sources,markChanged:async()=>{}},scheduler:{request:(/** @type {unknown[]} */ ...args)=>requests.push(args)}};
 const uri={scheme:'file',fsPath:file};await ui.changeWatcher(context).changed(uri);await sources.refresh([file]);assert.equal(sources.isGenerated(file),true);
 await io.writeFile(file,'class Stamped {}');await sources.refresh([file]);assert.equal(sources.isGenerated(file),false);
 await io.rm(file);await ui.changeWatcher(context).changed(uri,undefined,true);assert.equal(requests.length,1);
});

test('source refresh retains ignored semantic inputs and does not replace a newer event classification',async t=>{
 const root=await temporary(t),file=path.join(root,'Ignored.g.cs'),sources=new SourceTracker();
 await io.writeFile(file,'// <auto-generated/>\npartial class Hidden {}');sources.setFiles([], [file]);
 /** @type {any} */ const read=io.readFile; // any: wrapped below with a pass-through that gates one read
 /** @type {(value?: any) => void} */ let release=()=>{}; // replaced synchronously by the promise executor
 /** @type {(value?: any) => void} */ let ready=()=>{};
 const gate=new Promise(resolve=>release=resolve),started=new Promise(resolve=>ready=resolve);
 /** @type {any} */ (io).readFile=async(/** @type {any[]} */ ...args)=>{const bytes=await read(...args);if(args[0]===file){ready();await gate;}return bytes;};
 try {
  const refresh=sources.refresh([file]);await started;sources.observeGenerated(file,false);release();await refresh;
 }finally{io.readFile=read;release();}
 assert.equal(sources.isGenerated(file),false);assert.equal(sources.hashes.has(file),false);assert.ok(sources.analysisHashes.has(file));
 const previous=sources.analysisHashes.get(file);await io.writeFile(file,'partial class Hidden {}');await sources.refresh([file]);
 assert.notEqual(sources.analysisHashes.get(file),previous);assert.equal(sources.isGenerated(file),false);
 sources.setFiles([]);assert.equal(/** @type {any} */ (sources).classifications.has(file),false,'ordinary files leaving the graph need no retained tombstone');
});

test('directory-root exclusions cover create, rename and delete events while ordinary directories trigger',async t=>{
 const root=await temporary(t),ui=loadUi();
 /** @type {unknown[][]} */ const requests=[];
 // Partial ChangeWatcher host (any): only what the watcher reads.
 /** @type {any} */ const context={queueChanged(/** @type {string[]} */ files){void this.engine.markChanged(files);},roots:[root],config:{pattern:'**/*.{cs,csproj}',excludes:[...defaultExcludes,'ignored/**']},engine:{knownFiles:[],directories:[],markChanged:async()=>{}},scheduler:{request:(/** @type {unknown[]} */ ...args)=>requests.push(args)}};
 for(const name of ['bin','obj','.git','ignored']) {
  const file=path.join(root,name);await io.mkdir(file);const uri={scheme:'file',fsPath:file};
  await ui.changeWatcher(context).changed(uri,undefined,true);await io.rm(file,{recursive:true});await ui.changeWatcher(context).changed(uri,undefined,true);
 }
 assert.equal(requests.length,0);
 const ordinary=path.join(root,'Feature');await io.mkdir(ordinary);await ui.changeWatcher(context).changed({scheme:'file',fsPath:ordinary},undefined,true);
 context.engine.knownFiles=[path.join(ordinary,'Test.cs')];await io.rm(ordinary,{recursive:true});await ui.changeWatcher(context).changed({scheme:'file',fsPath:ordinary},undefined,true);
 assert.equal(requests.length,2);assert.ok(requests.every(([,full])=>full));
});
